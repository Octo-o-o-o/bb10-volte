"""Keep native fallback state text aligned with the phone runtime's bilingual text."""
import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'mobile/native/src/state_strings.h'


def state_messages():
    tree = ast.parse((ROOT / 'mobile/runtime/worker.py').read_text(encoding='utf-8'))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'MESSAGES' for t in node.targets):
            return ast.literal_eval(node.value)
    raise ValueError('Missing runtime state translations')


def rendered_header():
    lines = ['// Generated by tools/mobile_i18n.py --write; edit worker.MESSAGES instead.',
             '#ifndef BB10_STATE_STRINGS_H', '#define BB10_STATE_STRINGS_H',
             'struct UiStateString { const char *state; const char *zh[3]; const char *en[3]; };',
             'static const UiStateString UI_STATE_STRINGS[] = {']
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    for state, values in sorted(state_messages().items()):
        if len(values) != 6 or not all(isinstance(v, str) and v for v in values):
            raise ValueError('Incomplete translation: ' + state)
        lines.append('    {' + quote(state) + ', {' + ', '.join(map(quote, values[:3])) +
                     '}, {' + ', '.join(map(quote, values[3:])) + '}},')
    lines.extend(['    {0, {0, 0, 0}, {0, 0, 0}}', '};', '#endif', ''])
    return '\n'.join(lines)


def check_generated():
    if HEADER.read_text(encoding='utf-8') != rendered_header():
        raise ValueError('Native state translations differ; run tools/mobile_i18n.py --write')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    if args.write:
        HEADER.write_text(rendered_header(), encoding='utf-8', newline='\n')
    check_generated()
